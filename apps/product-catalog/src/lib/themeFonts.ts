/** Every family, flat, plus the no-download system stack. */
export const FONT_NAMES: readonly string[] = [...Object.values(FONT_CATALOG).flat(), 'system-ui'];

const CATEGORY_OF: ReadonlyMap<string, FontCategory> = new Map(
  (Object.entries(FONT_CATALOG) as [FontCategory, readonly string[]][]).flatMap(([c, list]) => list.map((n) => [n, c] as const)),
);

export function fontCategory(name: string): FontCategory | 'system' {
  return CATEGORY_OF.get(name) ?? 'system';
}

export interface FontPair {
  readonly id: string;
  readonly label: string;
  readonly vibe: string;
  readonly display: string;
  readonly body: string;
}

const pair = (id: string, display: string, body: string, vibe: string): FontPair => ({
  id,
  label: display === body ? display : `${display} + ${body}`,
  vibe,
  display,
  body,
});

