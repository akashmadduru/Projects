package com.acme.ecommerce.order.api.dto;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

public record OrderResponse(
    UUID id,
    String status,
    String currency,
    BigDecimal totalAmount,
    Instant placedAt,
    Instant cancelledAt,
    ShipToResponse shipTo,
    List<OrderItemResponse> items,
    UUID userId,
    String email,
    String paymentMethod,
    String paymentStatus,
    BigDecimal subtotalAmount,
    BigDecimal discountAmount,
    String couponCode,
    BigDecimal shippingAmount,
    BigDecimal taxAmount,
    String taxLabel,
    TaxBreakdownResponse taxBreakdown,
    LocalDate estimatedDeliveryDate,
    String trackingNumber,
    String carrier,
    Instant deliveredAt,
    boolean cancellable,
    boolean returnable,
    Instant returnWindowEndsAt,
    List<TimelineEntryResponse> timeline,
    PaymentBlockResponse payment,
    int coinsRedeemed,
    BigDecimal coinsValue,
    BigDecimal walletAmount,
    boolean membershipFreeShipping,
    List<ShipmentResponse> shipments,
    boolean riskHold,
    int riskScore,
    List<String> riskReasons,
    BigDecimal exchangeValue,
    BigDecimal exchangeShortfall,
    UUID exchangeQuoteId) {

  /** Copy with the payment block (CARD placement / replay) filled in. */
  public OrderResponse withPayment(PaymentBlockResponse block) {
    return new OrderResponse(
        id,
        status,
        currency,
        totalAmount,
        placedAt,
        cancelledAt,
        shipTo,
        items,
        userId,
        email,
        paymentMethod,
        paymentStatus,
        subtotalAmount,
        discountAmount,
        couponCode,
        shippingAmount,
        taxAmount,
        taxLabel,
        taxBreakdown,
        estimatedDeliveryDate,
        trackingNumber,
        carrier,
        deliveredAt,
        cancellable,
        returnable,
        returnWindowEndsAt,
        timeline,
        block,
        coinsRedeemed,
        coinsValue,
        walletAmount,
        membershipFreeShipping,
        shipments,
        riskHold,
        riskScore,
        riskReasons,
        exchangeValue,
        exchangeShortfall,
        exchangeQuoteId);
  }
}
